const pages = JSON.parse(readFileSync(pagesPath, 'utf8'));
const pagePaths = new Set(pages.map(({ path }) => path));

if (altByPath.size !== pages.length) {
  throw new Error(`Expected ${pages.length} alt descriptions, received ${altByPath.size}`);
}
for (const path of altByPath.keys()) {
  if (!pagePaths.has(path)) throw new Error(`Unknown knowledge-page path: ${path}`);
}

const updatedPages = pages.map((page) => ({
  ...page,
  imageAlt: altByPath.get(page.path),
}));
const manifest = updatedPages.map((page) => ({
  path: page.path,
  filename: page.image.split('/').at(-1),
  alt: page.imageAlt,
}));

writeFileSync(pagesPath, `${JSON.stringify(updatedPages, null, 2)}\n`);
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
